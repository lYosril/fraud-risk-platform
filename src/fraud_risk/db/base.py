"""Declarative base and shared ORM conventions.

Responsibility
    Define the ``DeclarativeBase`` subclass and the constraint/index naming convention so
    that autogenerated migrations are stable and readable.

Status
    Implemented for the prediction persistence layer. The schema is owned by Alembic;
    ``metadata.create_all()`` is never used by the application.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

#: Deterministic names for every constraint and index Alembic will render.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Shared SQLAlchemy declarative base."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


__all__ = ["NAMING_CONVENTION", "Base"]
